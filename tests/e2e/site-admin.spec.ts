import { test, expect, type Page } from "@playwright/test";

test.beforeEach(async ({ request }) => { await request.post("http://127.0.0.1:54329/__test/reset"); });
async function signIn(page: Page, administrator = true) {
  await page.goto("/login");
  await page.getByLabel("아이디", { exact: true }).fill(administrator ? "site.admin" : "kim.teacher");
  await page.getByLabel("비밀번호", { exact: true }).fill(administrator ? "Admin-password-2026!" : "teacher-password-2026");
  await page.getByRole("button", { name: "로그인", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
}

