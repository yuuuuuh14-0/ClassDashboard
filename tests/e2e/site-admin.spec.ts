test("administrator API rejects unauthenticated visitors, teachers, foreign origins, and stale edits", async ({ page, request }) => {
  expect((await request.get("/api/site-admin")).status()).toBe(401);
  await signIn(page, false);
  expect((await page.request.get("/api/site-admin")).status()).toBe(403);
  const mutation = { action: "create_school", name: "허용되지 않은 학교" };
  expect((await page.request.post("/api/site-admin", { headers: { Origin: "http://127.0.0.1:3100" }, data: mutation })).status()).toBe(403);
  await page.getByRole("button", { name: "로그아웃", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await signIn(page);
  expect((await page.request.post("/api/site-admin", { headers: { Origin: "https://other.example" }, data: mutation })).status()).toBe(403);
  const headers = { Origin: "http://127.0.0.1:3100" };
  expect((await page.request.post("/api/site-admin", { headers, data: { ...mutation, is_site_admin: true } })).status()).toBe(400);
  const created = await page.request.post("/api/site-admin", { headers, data: { action: "create_school", name: "충돌 검사 학교" } });
  expect(created.status()).toBe(200);
  const { id } = await created.json();
  expect((await page.request.post("/api/site-admin", { headers, data: { action: "save_school", id, name: "변경한 학교", version: 1 } })).status()).toBe(200);
  expect((await page.request.post("/api/site-admin", { headers, data: { action: "save_school", id, name: "오래된 변경", version: 1 } })).status()).toBe(409);
  const snapshot = await (await page.request.get("/api/site-admin")).json();
  expect(snapshot.schools[0].name).toBe("변경한 학교");
});
